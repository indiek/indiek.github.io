"""Generate the reference pages of indiek.org from the indiek package.

    uv run --project ../public_archive python scripts/sync_docs.py [PACKAGE_DIR]

Run from the site root; PACKAGE_DIR defaults to ``../public_archive``.

* ``docs/format.md``  <- ``src/indiek/spec/SPEC.md`` (the normative spec; the
  site never rewrites it, owner decision D19) + an appendix outlining
  ``MANIFEST.json``, built with the package itself.
* ``docs/sdk.md``     <- README.md: "Quickstart > With the SDK" and
  "Python SDK reference" (its examples are executed by the package tests).
* ``docs/cli.md``     <- README.md: "Quickstart > With the CLI", "`ik` CLI
  reference", "Integrity, seals and trust" and "Known limitations".

In-page links of the README are rewritten to point at the page that holds
the target heading; an unknown target stops the script.  Generated pages
must not be edited by hand.
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
DOCS = SITE / "docs"
NOTICE = "<!-- Generated by scripts/sync_docs.py from {source}. Do not edit by hand. -->"
# README anchors whose section is not copied to a generated page.
EXTERNAL_ANCHORS = {
    "install": "/docs/intro/#install",
    "concepts": "/docs/intro/#concepts",
    "the-archive-format": "/docs/format/",
    "contributing": "/docs/contributing/",
    "license": "/docs/license/",
}


@dataclass
class Heading:
    level: int
    title: str
    line: int


def gfm_id(title: str) -> str:
    """Heading id as generated by GitHub and kramdown's GFM parser."""
    text = title.replace("`", "").strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def headings(lines: list[str]) -> list[Heading]:
    found, fenced = [], False
    for number, line in enumerate(lines):
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and (match := re.match(r"^(#{1,6}) (.+)$", line)):
            found.append(Heading(len(match.group(1)), match.group(2).strip(), number))
    return found


def section(lines: list[str], title: str, *, body_only: bool = False) -> list[str]:
    """Lines of the section headed ``title`` (up to the next heading of the
    same or a higher level)."""
    all_headings = headings(lines)
    for index, heading in enumerate(all_headings):
        if heading.title == title:
            end = next(
                (h.line for h in all_headings[index + 1 :] if h.level <= heading.level),
                len(lines),
            )
            start = heading.line + 1 if body_only else heading.line
            return lines[start:end]
    raise SystemExit(f"README section not found: {title!r}")


def shift(lines: list[str], by: int) -> list[str]:
    """Change the level of every heading (outside code fences) by ``by``."""
    out, fenced = [], False
    for line in lines:
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and (match := re.match(r"^(#{1,6}) (.+)$", line)):
            line = "#" * (len(match.group(1)) + by) + " " + match.group(2)
        out.append(line)
    return out


def page_ids(lines: list[str]) -> set[str]:
    ids: set[str] = set()
    for heading in headings(lines):
        base, candidate, n = gfm_id(heading.title), gfm_id(heading.title), 0
        while candidate in ids:
            n += 1
            candidate = f"{base}-{n}"
        ids.add(candidate)
    return ids


def rewrite_links(pages: dict[str, list[str]]) -> dict[str, str]:
    ids = {name: page_ids(lines) for name, lines in pages.items()}

    def target(page: str, anchor: str) -> str:
        if anchor in ids[page]:
            return f"#{anchor}"
        for other, other_ids in ids.items():
            if anchor in other_ids:
                return f"/docs/{other}/#{anchor}"
        if anchor in EXTERNAL_ANCHORS:
            return EXTERNAL_ANCHORS[anchor]
        raise SystemExit(f"docs/{page}.md: link target #{anchor} not found")

    texts = {}
    for page, lines in pages.items():
        text = "\n".join(lines)
        text = re.sub(
            r"\]\(#([^)]+)\)", lambda m: f"]({target(page, m.group(1))})", text
        )
        text = text.replace("](https://indiek.org/", "](/")
        texts[page] = text
    return texts


def front_matter(title: str, description: str) -> str:
    return f'---\ntitle: "{title}"\ndescription: "{description}"\n---\n'


def write(name: str, title: str, description: str, source: str, body: str) -> None:
    path = DOCS / f"{name}.md"
    path.write_text(
        front_matter(title, description)
        + NOTICE.format(source=source)
        + "\n{% raw %}\n"
        + body.strip()
        + "\n{% endraw %}\n",
        encoding="utf-8",
    )
    print(f"Wrote {path.relative_to(SITE)}")


def manifest_appendix() -> str:
    from indiek.ops.manifest import build_manifest

    manifest = build_manifest(
        ["<64-hex public key of whoever ran ik manifest>"],
        {"hash": ["sha256"], "signature": ["ed25519"]},
    )
    schemas = manifest["schemas"]
    manifest["schemas"] = {
        name: schema if name == "LogTip" else "{ … JSON Schema … }"
        for name, schema in schemas.items()
    }
    rendered = json.dumps(manifest, indent=2, ensure_ascii=False)
    return (
        "\n\n## Appendix: outline of `MANIFEST.json`\n\n"
        "`ik manifest` writes this document at the archive root (informative, "
        "§17). Every schema is a JSON Schema generated from the reference "
        "implementation; only `LogTip` is shown in full here.\n\n"
        f"```json\n{rendered}\n```\n"
    )


def main() -> None:
    package = Path(sys.argv[1] if len(sys.argv) > 1 else SITE.parent / "public_archive")
    spec = (package / "src" / "indiek" / "spec" / "SPEC.md").read_text("utf-8")
    readme = (package / "README.md").read_text("utf-8").splitlines()

    sdk = [
        "# Python SDK reference",
        "",
        "The `indiek` package is the reference implementation of the IndieK "
        "archive format. Install it with `uv add indiek` (or `pip install indiek`); "
        "it needs Python 3.14 or newer and depends only on `pydantic` and `pynacl`. "
        "The examples below form one story: each builds on the previous ones.",
        "",
        "## Quickstart",
        *section(readme, "With the SDK", body_only=True),
        *shift(section(readme, "Python SDK reference", body_only=True), -1),
    ]
    cli = [
        "# `ik` command-line reference",
        "",
        "`ik` is the command-line tool of the `indiek` package. Install it with "
        "`uv tool install 'indiek[cli]'` (or `pip install 'indiek[cli]'`).",
        "",
        "## Quickstart",
        *section(readme, "With the CLI", body_only=True),
        *shift(section(readme, "`ik` CLI reference", body_only=True), -1),
        *section(readme, "Integrity, seals and trust"),
        *section(readme, "Known limitations"),
    ]
    texts = rewrite_links({"sdk": sdk, "cli": cli})
    source = "the indiek package README.md"
    write(
        "sdk",
        "Python SDK reference",
        "Complete reference of the indiek Python SDK.",
        source,
        texts["sdk"],
    )
    write(
        "cli",
        "ik CLI reference",
        "Complete reference of the ik command-line tool.",
        source,
        texts["cli"],
    )
    write(
        "format",
        "Format specification",
        "The normative specification of the IndieK archive format 3.0.",
        "the indiek package src/indiek/spec/SPEC.md",
        spec + manifest_appendix(),
    )


if __name__ == "__main__":
    main()
